  /**
   * Get the project root directory.
   *
   * @return string
   *   The project root path.
   */
  protected function getProjectRoot(): string {
    // Go up from web/ to project root.
    return dirname(\Drupal::root());
  }

  /**
   * Check if .gitignore file exists in project root.
   *
   * @return bool
   *   TRUE if .gitignore exists.
   */
  protected function hasGitignore(): bool {
    return file_exists($this->projectRoot . '/.gitignore');
  }

  /**
   * Check if git command is available.
   *
   * @return bool
   *   TRUE if git is available.
   */
  protected function gitAvailable(): bool {
    $process = new Process(['which', 'git']);
    $process->run();
    return $process->isSuccessful();
  }

  /**
   * Recursively scan directory for all files.
   *
   * @param string $directory
   *   The directory to scan.
   *
   * @return array
   *   Array of absolute file paths.
   */
  protected function recursiveFileScan(string $directory): array {
    $files = [];
    $iterator = new \RecursiveIteratorIterator(
      new \RecursiveDirectoryIterator($directory, \RecursiveDirectoryIterator::SKIP_DOTS),
      \RecursiveIteratorIterator::SELF_FIRST
    );

    foreach ($iterator as $file) {
      if ($file->isFile()) {
        $files[] = $file->getPathname();
      }
    }

    return $files;
  }

  /**
   * Check if file path is ignored by .gitignore using git check-ignore.
   *
   * @param string $relativePath
   *   The relative path from project root.
   *
   * @return bool
   *   TRUE if file is ignored.
   */
  protected function isIgnoredByGit(string $relativePath): bool {
    $process = new Process(['git', 'check-ignore', $relativePath], $this->projectRoot);
    $process->run();
    return $process->getExitCode() === 0;
  }

  /**
   * Check if path is a known dependency directory.
   *
   * @param string $path
   *   The relative path.
   *
   * @return bool
   *   TRUE if path is a dependency.
   */
  protected function isDependency(string $path): bool {
    $dependencies = [
      'vendor/',
      'node_modules/',
      'web/core/',
      'web/libraries/',
    ];

    foreach ($dependencies as $dep) {
      if (strpos($path, $dep) === 0) {
        return TRUE;
      }
    }
    return FALSE;
  }

  /**
   * Check if path is a regenerable file.
   *
   * @param string $path
   *   The relative path.
   *
   * @return bool
   *   TRUE if file is regenerable.
   */
  protected function isRegenerableFile(string $path): bool {
    $regenerables = [
      '#web/sites/.*/files/styles/#',
      '#web/sites/.*/files/css/#',
      '#web/sites/.*/files/js/#',
      '#web/sites/.*/files/php/#',
      '#web/sites/.*/files/advagg_#',
    ];

    foreach ($regenerables as $pattern) {
      if (preg_match($pattern, $path)) {
        return TRUE;
      }
    }
    return FALSE;
  }

  /**
   * Check if path contains sensitive configuration.
   *
   * @param string $path
   *   The relative path.
   *
   * @return bool
   *   TRUE if file is sensitive config.
   */
  protected function isSensitiveConfig(string $path): bool {
    $sensitiveFiles = [
      'settings.local.php',
      'settings.php',
      'services.yml',
      '.env',
      '.env.local',
    ];

    $filename = basename($path);
    if (in_array($filename, $sensitiveFiles)) {
      return TRUE;
    }

    // Pattern matches.
    $sensitivePatterns = ['*.key', '*.pem', '*.ppk'];
    foreach ($sensitivePatterns as $pattern) {
      $regex = str_replace('*', '.*', preg_quote($pattern, '/'));
      if (preg_match("/^{$regex}$/", $filename)) {
        return TRUE;
      }
    }

    return FALSE;
  }

  /**
   * Get the type of sensitive config file.
   *
   * @param string $path
   *   The relative path.
   *
   * @return string
   *   The config type.
   */
  protected function getSensitiveConfigType(string $path): string {
    $filename = basename($path);
    if (strpos($filename, 'settings') !== FALSE) {
      return 'Drupal settings';
    }
    if (strpos($filename, '.env') !== FALSE) {
      return 'Environment config';
    }
    if (strpos($filename, 'services') !== FALSE) {
      return 'Service configuration';
    }
    if (preg_match('/\.(key|pem|ppk)$/', $filename)) {
      return 'Private key/certificate';
    }
    return 'Sensitive configuration';
  }

  /**
   * Check if path is within private files directory.
   *
   * @param string $path
   *   The relative path.
   *
   * @return bool
   *   TRUE if file is in private directory.
   */
  protected function isPrivateFile(string $path): bool {
    $privatePath = $this->getPrivateFilesPath();
    if (empty($privatePath)) {
      return FALSE;
    }
    return strpos($path, $privatePath) === 0;
  }

  /**
   * Get the private files path from Drupal configuration.
   *
   * @return string|null
   *   The private files path or NULL if not configured.
   */
  protected function getPrivateFilesPath(): ?string {
    // Get private stream wrapper configuration.
    $private_path = \Drupal::service('stream_wrapper_manager')
      ->getViaScheme('private')
      ->getDirectoryPath();

    if ($private_path) {
      // Remove DRUPAL_ROOT prefix if present.
      $private_path = str_replace(\Drupal::root() . '/', '', $private_path);
      return $private_path;
    }

    return NULL;
  }

  /**
   * Check if path is within public files directory.
   *
   * @param string $path
   *   The relative path.
   *
   * @return bool
   *   TRUE if file is in public files directory.
   */
  protected function isPublicFile(string $path): bool {
    return (bool) preg_match('#^web/sites/[^/]+/files/#', $path);
  }

  /**
   * Format bytes into human-readable format.
   *
   * @param int $bytes
   *   The number of bytes.
   *
   * @return string
   *   Human-readable format (e.g., "1.5 MB").
   */
  protected function formatBytes(int $bytes): string {
    if ($bytes < 1024) {
      return $bytes . ' B';
    }
    elseif ($bytes < 1048576) {
      return round($bytes / 1024, 2) . ' KB';
    }
    elseif ($bytes < 1073741824) {
      return round($bytes / 1048576, 2) . ' MB';
    }
    else {
      return round($bytes / 1073741824, 2) . ' GB';
    }
  }

}
